#!/usr/bin/env bash
# Build the ready-to-run compose bundle attached to GitHub Releases.
# Usage: scripts/package-compose.sh <tag, e.g. v0.1.0> [output-dir, default: dist]
# Produces in <out>: compose.yaml and install.sh (standalone release assets), superhet-<tag>-compose.tar.gz,
# and a .sha256 next to each. The compose.yaml pulls ghcr.io/bxnnyg/superhet:${SUPERHET_TAG:-next|latest} instead of building.
set -euo pipefail
cd "$(dirname "$0")/.."

tag="${1:?usage: $0 <tag> [output-dir]}"
out="${2:-dist}"
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || { echo "invalid tag: $tag" >&2; exit 1; }
version="${tag#v}"
# Default moving image channel of this release: pre-releases follow `next` (newest release incl.
# pre-releases), stable releases follow `latest`. Override per install with SUPERHET_TAG in .env.
case "$version" in
*-*) channel=next ;;
*) channel=latest ;;
esac
image="${IMAGE:-ghcr.io/bxnnyg/superhet}"
image_ref="${image}:\${SUPERHET_TAG:-${channel}}"
name="superhet-${tag}-compose"

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
root="$stage/$name"
mkdir -p "$root/scripts" "$root/docs" "$root/deploy"

# Standalone compose.yaml from the dev one: no build block, the published image as default and
# the NATS config embedded via a top-level `configs:` entry (`content:`), so the file works on its
# own. Compose interpolates `content:`, hence every `$` is escaped to `$$` (NATS must still see
# $NATS_*_PASSWORD and read them from its environment).
standalone="$root/compose.yaml"
{
    printf '# Superhet %s - standalone stack (generated by scripts/package-compose.sh from compose.yaml).\n' "$tag"
    printf '# Needs a .env next to it with the random passwords; install.sh creates it.\n'
    awk '
        NR <= 3 && /^#/ { next }
        /^  build:$/ { skip = 1; next }
        skip && /^    / { next }
        { skip = 0 }
        /\.\/deploy\/nats\/nats\.conf:\/etc\/nats\/nats\.conf:ro/ { next }
        { print }
        /^    command: \["-js", "-c", "\/etc\/nats\/nats\.conf"\]$/ {
            print "    configs:"
            print "      - source: nats-conf"
            print "        target: /etc/nats/nats.conf"
        }
    ' compose.yaml |
        sed -e "s|\${SUPERHET_IMAGE:-superhet:dev}|\${SUPERHET_IMAGE:-${image_ref}}|" \
            -e 's|run scripts/gen-secrets.sh|missing in .env (re-run install.sh)|'
    printf '\nconfigs:\n  nats-conf:\n    content: |\n'
    sed -e 's/\$/$$/g' -e 's/^\(.\)/      \1/' deploy/nats/nats.conf
} >"$standalone"
if grep -q -e 'build:' -e 'superhet:dev' -e 'gen-secrets' -e './deploy/' "$standalone" ||
    ! grep -qF "$image_ref" "$standalone" || ! grep -q 'source: nats-conf' "$standalone"; then
    echo "compose.yaml transformation failed (did compose.yaml change shape?)" >&2
    exit 1
fi

# install.sh with the release tag as default version.
sed "s|@TAG@|${tag}|g" scripts/install.sh >"$stage/install.sh"
chmod 0755 "$stage/install.sh"
cp "$standalone" "$stage/compose.yaml"

cp -r deploy/udev deploy/modprobe "$root/deploy/"
install -m 0755 scripts/gen-secrets.sh "$root/scripts/gen-secrets.sh"
cp .env.example "$root/.env.example"
cp docs/setup-host.md "$root/docs/setup-host.md"
cp LICENSE NOTICE "$root/"
sed -e "s|@TAG@|${tag}|g" -e "s|@IMAGE@|${image}|g" -e "s|@CHANNEL@|${channel}|g" deploy/bundle/INSTALL.md >"$root/INSTALL.md"

mkdir -p "$out"
archive="$out/$name.tar.gz"
# Reproducible-ish: fixed order, no owner info, mtime from the commit when available.
mtime="$(git log -1 --format=%cI 2>/dev/null || date -u +%FT%TZ)"
tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="$mtime" -C "$stage" -czf "$archive" "$name"
(cd "$out" && sha256sum "$name.tar.gz" >"$name.tar.gz.sha256")
# Standalone assets next to the tarball (what install.sh downloads).
install -m 0644 "$stage/compose.yaml" "$out/compose.yaml"
install -m 0755 "$stage/install.sh" "$out/install.sh"
(cd "$out" && sha256sum compose.yaml >compose.yaml.sha256 && sha256sum install.sh >install.sh.sha256)
echo "$archive"
