#!/usr/bin/env bash
# Create .env with random passwords for the compose stack. Never overwrites an existing .env.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -e .env ]]; then
    echo ".env already exists; leaving it untouched" >&2
    exit 0
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

rand() { openssl rand -hex 24; }

umask 077
{
    echo "# Generated by scripts/gen-secrets.sh. Do not commit."
    for var in POSTGRES_PASSWORD NATS_API_PASSWORD NATS_SDRD_PASSWORD NATS_PLUGINHOST_PASSWORD NATS_WORKER_PASSWORD; do
        echo "$var=$(rand)"
    done
} >.env
echo "created .env with random passwords"
